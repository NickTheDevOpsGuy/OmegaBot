export function getTodayWord(): string {
  const today = new Date().toISOString().split("T")[0];
  const seed = today.split("-").join("");
  const index = parseInt(seed, 10) % WORDS.length;
  return WORDS[index];
}

/**
 * Determine the result for a letter in a guess.
 * - "correct": Letter is in the right position (🟩)
 * - "present": Letter is in the word but wrong position (🟨)
 * - "absent": Letter is not in the word (⬛)
 */
export function getLetterResult(
  guess: string,
  word: string,
  index: number,
): "correct" | "present" | "absent" {
  const letter = guess[index];
  if (word[index] === letter) return "correct";
  if (word.includes(letter)) return "present";
  return "absent";
}

export function formatGuessResults(
  guess: string,
  word: string,
): Array<"correct" | "present" | "absent"> {
  return guess.split("").map((_, i) => getLetterResult(guess, word, i));
}
